void draw(int x, int y, Icon icon, uint16_t color) {
    auto& d = M5.Display;
    for (int row = 0; row < H; row++) {
        const char* line = icon[row];
        if (!line) continue;
        for (int col = 0; col < W; col++) {
            if (line[col] == '#') {
                d.drawPixel(x + col, y + row, color);
            }
        }
    }
}

